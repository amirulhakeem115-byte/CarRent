  static String translate(BuildContext context, String input) {
    try {
      final isArabic =
          Provider.of<LanguageProvider>(context, listen: true).isArabic;
      if (isArabic) {
        if (_arMap.containsKey(input)) {
          return _arMap[input]!;
        }

        // Smart dynamic pattern translation for incoming notifications
        String translated = input;
        for (final entry in _dynamicNotificationPatterns.entries) {
          if (translated.contains(entry.key)) {
            translated = translated.replaceAll(entry.key, entry.value);
          }
        }
        if (translated != input) {
          return translated;
        }
        return input;
      }
    } catch (_) {}
    return input;
  }
